/// Каталог реакций: разделы эмодзи с ключевыми словами для поиска.
///
/// Записи хранятся строками «эмодзи слова; эмодзи слова» — так список
/// читается и правится глазами, а разбирается один раз при первом обращении.
class EmojiEntry {
  final String emoji;

  /// Слова для поиска в нижнем регистре, через пробел.
  final String keywords;

  const EmojiEntry(this.emoji, this.keywords);
}

class EmojiSection {
  final String title;

  /// Эмодзи на вкладке раздела.
  final String icon;
  final List<EmojiEntry> items;

  const EmojiSection(this.title, this.icon, this.items);
}

List<EmojiEntry> _parse(String raw) {
  final out = <EmojiEntry>[];
  for (final part in raw.split(';')) {
    final t = part.trim();
    if (t.isEmpty) continue;
    final space = t.indexOf(' ');
    out.add(space < 0 ? EmojiEntry(t, '') : EmojiEntry(t.substring(0, space), t.substring(space + 1).toLowerCase()));
  }
  return out;
}

