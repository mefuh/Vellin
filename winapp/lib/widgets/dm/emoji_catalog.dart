/// Поиск по словам: каждое слово запроса должно найтись в описании эмодзи.
List<EmojiEntry> searchEmoji(String query) {
  final words = query.toLowerCase().split(RegExp(r'\s+')).where((w) => w.isNotEmpty).toList();
  if (words.isEmpty) return const [];
  final seen = <String>{};
  final out = <EmojiEntry>[];
  for (final s in emojiSections) {
    for (final e in s.items) {
      if (words.every((w) => e.keywords.contains(w) || e.emoji == w) && seen.add(e.emoji)) out.add(e);
    }
  }
  return out;
}

/// Запасной шрифт — только для смайлика, которого нет среди картинок Apple
/// (пришёл реакцией с другого клиента).
const emojiFontFamily = 'Segoe UI Emoji';

/// Смайлик в рисовке Apple. Картинка вместо шрифта: системный шрифт Windows
/// рисует смайлики в своём стиле, а нужен вид Apple.
class EmojiGlyph extends StatelessWidget {
  final String emoji;
  final double size;

  const EmojiGlyph(this.emoji, {super.key, required this.size});

  /// Те же картинки по смайлику без селектора вида U+FE0F: другие клиенты
  /// шлют «❤» и «❤️» вперемешку, а рисоваться они должны одинаково.
  static final Map<String, String> _bare = {
    for (final e in appleEmojiAssets.entries) e.key.replaceAll('\u{fe0f}', ''): e.value,
  };

  @override
  Widget build(BuildContext context) {
    final file = appleEmojiAssets[emoji] ?? _bare[emoji.replaceAll('\u{fe0f}', '')];
    if (file == null) {
      return SizedBox(
        width: size,
        height: size,
        child: Center(
          child: Text(emoji, style: TextStyle(fontFamily: emojiFontFamily, fontSize: size * 0.82, height: 1)),
        ),
      );
    }
    return Image.asset(
      'assets/emoji/apple/$file',
      width: size,
      height: size,
      // Картинки 64 px, показываются мельче — сглаживание нужно, иначе края
      // рвутся лесенкой.
      filterQuality: FilterQuality.medium,
      gaplessPlayback: true,
    );
  }
}
