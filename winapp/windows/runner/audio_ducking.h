#ifndef RUNNER_AUDIO_DUCKING_H_
#define RUNNER_AUDIO_DUCKING_H_

// Отказ от системного приглушения звука на время разговора.
//
// Windows приглушает все остальные звуки, как только приложение открывает
// микрофон: по умолчанию — на 80 %. Из-за этого во время звонка тише
// становилась и музыка, и игра, а при демонстрации со звуком собеседник слышал
// уже приглушённый звук — захват идёт после приглушения.
//
// Вызывать один раз при запуске, до того как поднимется микрофон.
void DisableCommunicationsDucking();

#endif  // RUNNER_AUDIO_DUCKING_H_
